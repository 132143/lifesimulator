    # ------------------------------------------------------------------
    # 每日事件接管：在伦敦出生时，用本模组事件池强制替换原版抽签
    # ------------------------------------------------------------------
    def daily_event_hook(self, player, dice):
        # 仅接管“伦敦”开局
        city = getattr(player, "city", None) or getattr(player, "city_id", None)
        if city not in ("hp_london", "伦敦"):
            return None

        # 从已注册事件库里取出本模组、且满足当前条件的事件
        pool = []
        for eid, ev in EVENTS.items():
            if not str(eid).startswith("hp_"):
                continue
            try:
                if ev.get("cond") and not ev["cond"](player):
                    continue
            except Exception:
                continue
            w = int(ev.get("weight", 1000))
            pool.extend([eid] * max(1, w // 200))

        if not pool:
            return None

        rng = random.Random(dice if isinstance(dice, int) else None)
        chosen = rng.choice(pool)
        return chosen  # 返回事件 id，强制触发，全面接管原版每日事件

    # ------------------------------------------------------------------
    # 每天结束额外处理（轻微的魔法氛围，不改变核心数值）
    # ------------------------------------------------------------------
    def on_day_end(self, player, report):
        city = getattr(player, "city", None) or getattr(player, "city_id", None)
        if city not in ("hp_london", "伦敦"):
            return
        # 巫师寿命较长、医疗条件好，暮年阶段不额外扣减（交由底层逻辑处理）
        return None
