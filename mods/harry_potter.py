# ---------------------------------------------------------------------------
# 事件构造辅助
# ---------------------------------------------------------------------------
def _ev(eid, name, category, cond, descs, choices, weight=1000, tone="neutral",
        tags=None):
    return {
        "id": eid,
        "name": name,
        "category": category,
        "weight": weight,
        "descs": descs if isinstance(descs, list) else [descs],
        "cond": cond,
        "tone": tone,
        "special": False,
        "tags": tags or [],
        "choices": choices,
    }


def _choice(label, outcomes, hint="", roll="d10", need_money=0, need_disease=False):
    return {
        "label": label,
        "hint": hint,
        "roll": roll,
        "outcomes": outcomes,
        "need_money": need_money,
        "need_disease": need_disease,
    }


def _oc(rng, desc, effects=None, tone="neutral", next_event=None):
    o = {"range": rng, "desc": desc, "tone": tone}
    if effects:
        o["effects"] = effects
    if next_event:
        o["next_event"] = next_event
    return o


# 年龄区间条件
def _age(lo, hi=None):
    if hi is None:
        return lambda p: p.age >= lo
    return lambda p: lo <= p.age <= hi


